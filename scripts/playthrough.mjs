import assert from 'node:assert/strict';
export default async function(play){
 const read=()=>play.state('pulse.game');
 await play.screenshot('desktop-ak47');
 await play.page.getByRole('button',{name:'进入训练场'}).click();
 await play.waitFor(s=>s.phase==='playing',{read:'pulse.game'});
 await play.advance(.1,{read:'pulse.game'});
 await play.page.bringToFront();
 await play.mouse.click([.5,.5]);
 await play.waitFor(s=>s.active&&!s.mobile,{read:'pulse.game',timeoutMs:5000});
 assert.equal((await read()).shots,0,'pointer-lock click must not fire');
 const desktopShots=(await read()).shots;
 await play.page.mouse.down();await play.waitFor(s=>s.shots>desktopShots,{read:'pulse.game'});await play.page.mouse.up();
 await play.screenshot('desktop-fire');
 const pos=(await read()).position;
 await play.keyboard.hold('KeyW',500);
 assert(Math.hypot((await read()).position[0]-pos[0],(await read()).position[2]-pos[2])>.1);
 await play.keyboard.press('Digit2');await play.waitFor(s=>s.selected===1,{read:'pulse.game'});
 await play.page.mouse.down({button:'right'});await play.waitFor(s=>s.aiming,{read:'pulse.game'});await play.screenshot('desktop-scope');await play.page.mouse.up({button:'right'});
 await play.keyboard.press('Digit1');await play.waitFor(s=>s.selected===0,{read:'pulse.game'});
 await play.page.keyboard.press('Escape');
 // The same real UI accepts touch intent on compact screens; no state mutation or synthetic shots.
 const device=await play.page.context().newCDPSession(play.page);
 await device.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
 await play.page.setViewportSize({width:844,height:390});
 await play.page.touchscreen.tap(12,12);
 await play.waitFor(s=>s.mobile&&s.active,{read:'pulse.game'});
 await play.screenshot('mobile-ak47');
 console.log('mobile pointer lock',await play.page.evaluate(()=>document.pointerLockElement?.tagName??null));
 await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});await play.screenshot('ak47-inspect');await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>!s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});
 const fire=play.page.getByRole('button',{name:'射击',exact:true});
 let before=await read();await fire.click({delay:180});
 await play.waitFor(s=>s.shots>before.shots,{read:'pulse.game'});
 assert((await read()).ammo<30);
 await play.screenshot('ak47-fired');
 await play.page.getByRole('button',{name:'换弹',exact:true}).click();
 await play.waitFor(s=>s.reloading,{read:'pulse.game'});
 await play.screenshot('ak47-reloading');
 await play.advance(2.5,{read:'pulse.game'});assert.equal((await read()).ammo,30);
 await play.page.locator('[data-weapon="1"]').click();await play.waitFor(s=>s.selected===1,{read:'pulse.game'});
 await play.advance(.3,{read:'pulse.game'});await play.screenshot('awm-model');
 await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});await play.screenshot('awm-inspect');await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>!s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});
 before=await read();await fire.click({delay:180});await play.waitFor(s=>s.shots>before.shots,{read:'pulse.game'});assert.equal((await read()).ammo,4);
 await play.page.getByRole('button',{name:'瞄准',exact:true}).click();await play.waitFor(s=>s.aiming,{read:'pulse.game'});await play.screenshot('awm-scope');
 await play.page.locator('[data-weapon="2"]').click();await play.waitFor(s=>s.selected===2&&!s.aiming,{read:'pulse.game'});await play.advance(.3,{read:'pulse.game'});await play.screenshot('glock-model');
 await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});await play.screenshot('glock-inspect');await play.page.getByRole('button',{name:'检视武器',exact:true}).click({timeout:5000}).catch(error=>{console.log(error.message);throw error;});await play.waitFor(s=>!s.inspecting,{read:'pulse.game'});await play.advance(.6,{read:'pulse.game'});
 before=await read();await fire.click({delay:180});await play.waitFor(s=>s.shots>before.shots,{read:'pulse.game'});assert.equal((await read()).ammo,16);
 await play.screenshot('glock-fired');
 await play.page.setViewportSize({width:390,height:844});await play.screenshot('portrait-glock');
 await play.reload();await play.page.waitForSelector('html[data-forgeax-input="open"]');assert.equal((await read()).selected,0);assert.equal((await read()).ammo,30);
 await play.screenshot('reload-clean');return{weapons:3,fire:'all three',reload:'passed',scope:'passed',mobile:'landscape and portrait'};
}
